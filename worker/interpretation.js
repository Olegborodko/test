const SYSTEM_HOUSE_NOTE = {
  western: 'Дома считаются от асцендента по Плацидусу.',
  vedic: 'Дома считаются от асцендента по целым знакам.',
};

function signName(sign) {
  return SIGN_NAMES[sign] || sign;
}

function housePhrase(house) {
  return HOUSES[house] ? `Сфера — ${HOUSES[house]}.` : '';
}

export function buildReading({ system, planets, ascendantSignIndex, ascendantLongitude }) {
  const ascSign = SIGNS[ascendantSignIndex];
  const sun = planets.find((planet) => planet.key === 'sun');
  const moon = planets.find((planet) => planet.key === 'moon');

  const sections = [
    { title: 'Кто ты', text: SUN_IN_SIGN[sun.sign] },
    { title: 'Что ты чувствуешь', text: MOON_IN_SIGN[moon.sign] },
    {
      title: 'Как тебя видят',
      text: ASC_SIGN[ascSign],
      note: `Твой восход — ${signName(ascSign)}. ${SYSTEM_HOUSE_NOTE[system] || ''}`.trim(),
    },
  ];

  if (system === 'vedic' && moon.nakshatra) {
    sections.push({
      title: 'Луна по-ведически',
      text: `Твоя Луна в сидерическом зодиаке — ${signName(moon.sign)}, накшатра ${moon.nakshatra}, пада ${moon.pada}. В ведической традиции именно Луна, а не Солнце, отвечает за ум и привычки.`,
    });
  }

  const others = planets
    .filter((planet) => planet.key !== 'sun' && planet.key !== 'moon')
    .map((planet) => {
      const info = PLANETS[planet.key];
      return `${info.title} — ${info.meaning}. В знаке ${signName(planet.sign)} это звучит так: ${SIGN_STYLE[planet.sign]}. ${housePhrase(planet.house)}`;
    });

  sections.push({ title: 'Остальные планеты', items: others });

  return { ascendant: { sign: ascSign, degreeInSign: ascendantLongitude % 30 }, system, sections };
}
