function signName(sign) {
  return SIGN_NAMES[sign] || sign;
}

function planetLine(planet) {
  const house = HOUSES[planet.house] || '';

  const signText = SIGN_TEXT_BY_PLANET[planet.key];
  if (GENERATIONAL.includes(planet.key) || !signText) {
    return `${PLANETS[planet.key]} У тебя это в знаке ${signName(planet.sign)}. ${house}`.trim();
  }

  return `${PLANETS[planet.key]} ${signText[planet.sign]} ${house}`.trim();
}

function retrogradeNote(planets) {
  const names = planets
    .filter((planet) => planet.retrograde && planet.key !== 'rahu')
    .map((planet) => PLANETS[planet.key].split(' — ')[0]);

  if (!names.length) return '';
  return `Ретроградными в момент рождения были: ${names.join(', ')}. Это не поломка — так бывает у всех; такие темы больше про внутреннее, чем про показное.`;
}

function synastryLine(aspect) {
  const text = SYNASTRY_ASPECTS[aspect.type];
  const first = PLANET_CASES[aspect.first];
  const second = PLANET_CASES[aspect.second];
  if (!text || !first || !second) return '';

  const subject = `${first.possessive} ${first.nominative} и ${second.nominative} партнёра`;
  const meaning = aspect.first === aspect.second
    ? 'эта тема у вас общая и работает одинаково'
    : `${PLANET_THEMES[aspect.first]} и ${PLANET_THEMES[aspect.second]} ${text.meaning}`;

  return `${subject} — ${text.label} (${text.term}): ${meaning}.`;
}

/** Ready-to-render synastry: one dated line is not needed here, the texts are enough. */
export function buildSynastry({ aspects, truncated, score }) {
  const items = aspects.map(synastryLine).filter(Boolean);
  return {
    title: 'Совместимость',
    note: truncated ? `${SYNASTRY_NOTE} Показаны 12 самых точных связей.` : SYNASTRY_NOTE,
    items,
    score,
  };
}

function transitLine(event) {
  const aspect = TRANSIT_ASPECTS[event.aspect];
  const transit = PLANET_CASES[event.transit];
  const natal = PLANET_CASES[event.natal];
  if (!aspect || !transit || !natal) return '';

  const themes = NATAL_THEMES[event.natal];
  const theme = aspect.themeCase === 'ins' ? themes[1] : themes[0];
  const subject = event.transit === event.natal ? `${transit.nominative} на небе` : transit.nominative;
  return `${subject} ${aspect.phrase} ${natal[aspect.nameCase]} в карте (${aspect.term}): ${TRANSIT_THEMES[event.transit]} ${aspect.verb} ${theme}.`;
}

/** Ready-to-render forecast: a title, a note and one dated line per exact transit. */
export function buildForecast({ period, events, truncated }) {
  const items = events.map((event) => ({ date: event.date, text: transitLine(event) })).filter((item) => item.text);

  return {
    title: PERIOD_TITLES[period] || PERIOD_TITLES.month,
    note: truncated ? `${FORECAST_NOTE} Показаны ближайшие события.` : FORECAST_NOTE,
    items,
  };
}

function aspectLine(aspect) {
  const text = ASPECT_TEXTS[aspect.type];
  const from = PLANET_CASES[aspect.from];
  const to = PLANET_CASES[aspect.to];
  if (!text || !from || !to) return '';
  const label = text.label(from, to);
  const themes = `${PLANET_THEMES[aspect.from]} и ${PLANET_THEMES[aspect.to]}`;
  return `${label}: ${themes} ${text.meaning}.`;
}

export function buildReading({ system, planets, ascendantSignIndex, aspects = [] }) {
  const ascSign = SIGNS[ascendantSignIndex];
  const sun = planets.find((planet) => planet.key === 'sun');
  const moon = planets.find((planet) => planet.key === 'moon');

  // timeSensitive marks the parts that move when the birth time is off: the
  // ascendant, the house cusps and the Moon (it walks ~0,5° per hour).
  const sections = [
    { title: 'Кто ты', text: SUN_IN_SIGN[sun.sign] },
    { title: 'Что ты чувствуешь', text: MOON_IN_SIGN[moon.sign] },
    {
      title: 'Как тебя видят',
      text: ASC_SIGN[ascSign],
      note: `Твой восход — ${signName(ascSign)}. ${SYSTEM_HOUSE_NOTE[system] || ''}`.trim(),
    },
  ];

  if (system === 'vedic' && moon.nakshatra) {
    sections.push({
      title: 'Луна по-ведически',
      text: `Твоя Луна в сидерическом зодиаке — ${signName(moon.sign)}, накшатра ${moon.nakshatra}, пада ${moon.pada}. В ведической традиции именно Луна, а не Солнце, отвечает за ум и привычки.`,
    });
  }

  const others = planets
    .filter((planet) => planet.key !== 'sun' && planet.key !== 'moon')
    .map(planetLine);

  const hasAsteroids = planets.some((planet) => ASTEROID_KEYS.includes(planet.key));
  const asteroidNote = hasAsteroids
    ? 'Астероиды добавляют оттенки, но главные темы карты читаются по большим планетам.'
    : '';

  sections.push({
    title: 'Остальные планеты',
    items: others,
    note: [GENERATION_NOTE, asteroidNote, retrogradeNote(planets)].filter(Boolean).join(' '),
  });

  const aspectItems = aspects.map(aspectLine).filter(Boolean);
  if (aspectItems.length) {
    const shown = aspectItems.slice(0, MAX_ASPECTS);
    const note = aspectItems.length > shown.length
      ? `${ASPECTS_NOTE} Показаны ${MAX_ASPECTS} самых точных связей.`
      : ASPECTS_NOTE;
    sections.push({ title: 'Связи планет', items: shown, note });
  }

  return { ascendant: { sign: ascSign }, system, sections };
}
